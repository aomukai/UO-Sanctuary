#!/usr/bin/env python3
"""Compile the Sanctuary skill icon atlases into ClassicUO gumps and a shared ID map."""

import argparse
from itertools import groupby
import json
from pathlib import Path
import re
from struct import pack

from PIL import Image, ImageDraw, ImageOps


ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art/skill-icons"
SIZE = 44


def load_catalog():
    catalog = json.loads((ROOT / "data/Sanctuary/Balance/class-skills.json").read_text())
    return {row["talentId"]: row for row in catalog}


def spell_tile(atlas, box):
    gray = ImageOps.grayscale(atlas.crop(box))
    ink = gray.point(lambda level: max(0, min(255, (238 - level) * 255 // 206)))
    bounds = ink.point(lambda level: 255 if level >= 85 else 0).getbbox()
    if bounds is None:
        raise ValueError(f"Empty atlas cell at {box}")
    margin = 4
    left, top, right, bottom = bounds
    ink = ink.crop((max(0, left - margin), max(0, top - margin),
                    min(ink.width, right + margin), min(ink.height, bottom + margin)))
    ink.thumbnail((36, 36), Image.Resampling.LANCZOS)
    ink = ink.point(lambda level: round(255 * (level / 255) ** 0.78))

    tile = Image.new("RGB", (SIZE, SIZE), (205, 189, 144))
    draw = ImageDraw.Draw(tile)
    for y in range(3, SIZE - 3):
        for x in range(3, SIZE - 3):
            shade = ((x * 73 ^ y * 37 ^ x * y * 11) % 9) - 7
            draw.point((x, y), (205 + shade, 189 + shade, 144 + shade))
    for inset, color in enumerate(((41, 32, 24), (131, 115, 90), (41, 32, 24))):
        draw.rectangle((inset, inset, SIZE - inset - 1, SIZE - inset - 1), outline=color)
    tile.paste((41, 32, 24), ((SIZE - ink.width) // 2, (SIZE - ink.height) // 2), ink)
    return tile


def encode_gump(tile):
    """ClassicUO loose gump format, with a header and RGB555 runs for each row."""
    offsets = []
    runs = []
    for y in range(SIZE):
        offsets.append(SIZE + len(runs))
        colors = ((r >> 3) << 10 | (g >> 3) << 5 | (b >> 3)
                  for r, g, b in tile.crop((0, y, SIZE, y + 1)).getdata())
        for color, pixels in groupby(colors):
            runs.append(pack("<HH", color, sum(1 for _ in pixels)))
    return pack(f"<II{SIZE}I", SIZE, SIZE, *offsets) + b"".join(runs)


def products():
    manifest = json.loads((ART / "manifest.json").read_text())
    custom_base = manifest["customBase"]
    catalog = load_catalog()
    ability_names = {
        int(number): name for name, number in
        re.findall(r"^    (\w+) = (\d+),$", (ROOT / "shared/ClassAbilities.cs").read_text(), re.M)
    }
    gumps = {}
    icon_ids = {}

    def add(talent, graphic):
        if talent not in catalog or talent in icon_ids:
            raise ValueError(f"Unknown or duplicate talent {talent}")
        icon_ids[talent] = graphic

    for talent, graphic in manifest["native"].items():
        graphic = int(graphic, 16)
        if not 0 < graphic < custom_base:
            raise ValueError(f"Invalid native gump {graphic} for {talent}")
        add(talent, graphic)
    for name, entry in manifest["atlases"].items():
        with Image.open(ART / "sources" / f"{name}.png") as source:
            atlas = source.convert("RGB")
        columns = entry["columns"]
        rows = entry["rows"]
        if len(entry["cells"]) > columns * rows:
            raise ValueError(f"Too many {name} atlas cells")
        for index, talent in enumerate(entry["cells"]):
            if talent is None:
                continue
            row, column = divmod(index, columns)
            box = (column * atlas.width // columns, row * atlas.height // rows,
                   (column + 1) * atlas.width // columns, (row + 1) * atlas.height // rows)
            box = tuple(entry.get("crops", {}).get(str(index), box))
            graphic = custom_base + catalog[talent]["ability"]
            add(talent, graphic)
            gumps[ART / "gumps" / f"{graphic}.gump"] = encode_gump(spell_tile(atlas, box))

    missing = catalog.keys() - icon_ids.keys()
    if missing:
        raise ValueError(f"Missing icon mappings for {', '.join(sorted(missing))}")
    native_attack = int(manifest["basicAttack"], 16)
    lines = [
        "// Generated by tools/build_skill_icons.py from art/skill-icons/manifest.json.",
        "using System.Collections.Generic;",
        "using System.Linq;",
        "",
        "namespace Sanctuary;",
        "",
        "internal static class ClassSkillIcons",
        "{",
        "    private static readonly Dictionary<string, ushort> _byTalent =",
        "        ClassAbilities.Skills.ToDictionary(skill => skill.TalentId, skill => For(skill.Ability));",
        "",
        "    public static ushort ForTalent(string talentId) => _byTalent.GetValueOrDefault(talentId);",
        "",
        "    public static ushort For(CombatAbility ability) => ability switch",
        "    {",
        f"        CombatAbility.BasicAttack => 0x{native_attack:04X},",
    ]
    for talent, graphic in sorted(icon_ids.items(), key=lambda entry: catalog[entry[0]]["ability"]):
        ability = ability_names[catalog[talent]["ability"]]
        lines.append(f"        CombatAbility.{ability} => 0x{graphic:04X},")
    lines.extend(("        _ => 0,", "    };", "}", ""))
    inventory = [
        {
            "talentId": talent,
            "name": row["name"],
            "characterClass": row["characterClass"],
            "talentIcon": "mapped",
            "hotkeyIcon": "not-applicable" if row["passive"] else "mapped",
            "generation": "uo" if talent in manifest["native"] else "imagegen",
            "clientMapping": "mapped",
            "gumpId": f"0x{icon_ids[talent]:04X}",
        }
        for talent, row in catalog.items()
    ]
    outputs = gumps | {
        ROOT / "shared/ClassSkillIcons.cs": "\n".join(lines).encode(),
        ROOT / "data/Sanctuary/Balance/skill-icons.json": (json.dumps(inventory, indent=2) + "\n").encode(),
    }
    return outputs, len(icon_ids), len(gumps)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs, total, custom = products()
    extras = set((ART / "gumps").glob("*.gump")) - outputs.keys()
    if extras:
        raise SystemExit("Unmapped compiled gump(s): " + ", ".join(sorted(path.name for path in extras)))
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                raise SystemExit(f"Stale skill icon output: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"{total} talent icons verified. {custom} Sanctuary gumps and {total - custom} native UO mappings.")


if __name__ == "__main__":
    main()
